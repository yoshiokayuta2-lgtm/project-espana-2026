-- Signed-out visitors should not read/write app tables.
revoke all on public.assignments from anon;
revoke all on public.students from anon;
revoke all on public.student_secrets from anon;
revoke all on public.student_devices from anon;
revoke all on public.submissions from anon;

-- Authenticated users need operation grants; RLS below restricts rows by role.
grant select, insert, update, delete on public.assignments to authenticated;
grant select, insert, update, delete on public.students to authenticated;
grant select, insert, update, delete on public.student_secrets to authenticated;
grant select, insert, update, delete on public.student_devices to authenticated;
grant select, insert, update, delete on public.submissions to authenticated;

-- assignments
 drop policy if exists "teacher full assignments" on public.assignments;
create policy "teacher full assignments"
on public.assignments for all to authenticated
using (public.is_teacher())
with check (public.is_teacher());

drop policy if exists "student read published assignments" on public.assignments;
create policy "student read published assignments"
on public.assignments for select to authenticated
using (
  not public.is_teacher()
  and published = true
  and exists (
    select 1 from public.students s
    where s.id = public.current_student_id()
      and s.active = true
      and assignments.subject = any(s.subjects)
  )
);

-- students
 drop policy if exists "teacher full students" on public.students;
create policy "teacher full students"
on public.students for all to authenticated
using (public.is_teacher())
with check (public.is_teacher());

drop policy if exists "student read self" on public.students;
create policy "student read self"
on public.students for select to authenticated
using (id = public.current_student_id());

-- student_secrets: teacher only. student-login Edge Function uses server-side secret key and bypasses RLS.
 drop policy if exists "teacher full student secrets" on public.student_secrets;
create policy "teacher full student secrets"
on public.student_secrets for all to authenticated
using (public.is_teacher())
with check (public.is_teacher());


-- Edge Function server-side privileges (student-login)
grant usage on schema public to service_role;
grant select on table public.students to service_role;
grant select on table public.student_secrets to service_role;
grant select, insert, update, delete on table public.student_devices to service_role;
grant usage, select on sequence public.student_devices_id_seq to service_role;

-- student_devices: teacher can inspect/delete. Edge Function creates mappings with server-side secret key.
 drop policy if exists "teacher full student devices" on public.student_devices;
create policy "teacher full student devices"
on public.student_devices for all to authenticated
using (public.is_teacher())
with check (public.is_teacher());

-- submissions
 drop policy if exists "teacher full submissions" on public.submissions;
create policy "teacher full submissions"
on public.submissions for all to authenticated
using (public.is_teacher())
with check (public.is_teacher());

drop policy if exists "student read own submissions" on public.submissions;
create policy "student read own submissions"
on public.submissions for select to authenticated
using (
  student_id = public.current_student_id()
  and exists (select 1 from public.students s where s.id = public.current_student_id() and s.active = true)
);

drop policy if exists "student insert own submissions" on public.submissions;
create policy "student insert own submissions"
on public.submissions for insert to authenticated
with check (
  student_id = public.current_student_id()
  and status in ('draft','submitted')
  and exists (
    select 1 from public.assignments a
    join public.students s on s.id = public.current_student_id()
    where a.id = submissions.assignment_id
      and a.published = true
      and s.active = true
      and a.subject = any(s.subjects)
  )
);

drop policy if exists "student update own submissions" on public.submissions;
create policy "student update own submissions"
on public.submissions for update to authenticated
using (
  student_id = public.current_student_id()
  and exists (select 1 from public.students s where s.id = public.current_student_id() and s.active = true)
)
with check (student_id = public.current_student_id());

-- Anonymous students may edit their own learning fields, but may not forge teacher feedback/return state.
create or replace function public.protect_submission_teacher_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.is_teacher() then
    return new;
  end if;

  if new.student_id is distinct from old.student_id
     or new.assignment_id is distinct from old.assignment_id
     or new.feedback is distinct from old.feedback
     or new.returned_at is distinct from old.returned_at then
    raise exception 'teacher-owned submission fields cannot be changed by students';
  end if;

  if new.status = 'returned' then
    raise exception 'students cannot mark a submission as returned';
  end if;

  return new;
end;
$$;

drop trigger if exists protect_submission_teacher_fields_trigger on public.submissions;
create trigger protect_submission_teacher_fields_trigger
before update on public.submissions
for each row execute function public.protect_submission_teacher_fields();

