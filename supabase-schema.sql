-- worksheet-pdfs: teacher manages; students can read PDFs for published assignments in their subjects.
 drop policy if exists "teacher manage worksheet pdfs" on storage.objects;
create policy "teacher manage worksheet pdfs"
on storage.objects for all to authenticated
using (bucket_id = 'worksheet-pdfs' and public.is_teacher())
with check (bucket_id = 'worksheet-pdfs' and public.is_teacher());

 drop policy if exists "student read allowed worksheet pdfs" on storage.objects;
create policy "student read allowed worksheet pdfs"
on storage.objects for select to authenticated
using (
  bucket_id = 'worksheet-pdfs'
  and exists (
    select 1
    from public.assignments a
    join public.students s on s.id = public.current_student_id()
    where a.id::text = (storage.foldername(name))[1]
      and a.published = true
      and s.active = true
      and a.subject = any(s.subjects)
  )
);

