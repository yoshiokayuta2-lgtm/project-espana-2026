create policy "teacher manage answer images"
on storage.objects for all to authenticated
using (bucket_id = 'answer-images' and public.is_teacher())
with check (bucket_id = 'answer-images' and public.is_teacher());

 drop policy if exists "student read own answer images" on storage.objects;
create policy "student read own answer images"
on storage.objects for select to authenticated
using (
  bucket_id = 'answer-images'
  and (storage.foldername(name))[1] = auth.uid()::text
);

