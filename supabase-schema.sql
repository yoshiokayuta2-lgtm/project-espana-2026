-- =========================================================
-- Tables
-- =========================================================

create table if not exists public.assignments (
  id uuid primary key default gen_random_uuid(),
  subject text not null default 'japanese' check (subject in ('japanese','world')),
  title text not null,
  theme text,
  goal text,
  method text,
  source text,
  prompt text not null,
  char_limit integer not null default 50 check (char_limit between 1 and 2000),
  min_ratio numeric not null default 0.8,
  before_fields jsonb not null default '[]'::jsonb,
  required_elements jsonb not null default '[]'::jsonb,
  answer_flow text,
  teacher_model text,
  worksheet_pdf_path text,
  worksheet_pdf_name text,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.students (
  id uuid primary key default gen_random_uuid(),
  display_name text not null,
  subjects text[] not null default array['japanese','world']::text[],
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ログインコードは生徒本人からも直接読めない別テーブルに分離
create table if not exists public.student_secrets (
  student_id uuid primary key references public.students(id) on delete cascade,
  login_code text not null,
  updated_at timestamptz not null default now()
);

-- 生徒1人を複数端末から使えるよう、匿名Authユーザーとの紐付けを端末単位で保持
create table if not exists public.student_devices (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.students(id) on delete cascade,
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(auth_user_id)
);
create index if not exists student_devices_student_id_idx on public.student_devices(student_id);

create table if not exists public.submissions (
  id uuid primary key default gen_random_uuid(),
  assignment_id uuid not null references public.assignments(id) on delete cascade,
  student_id uuid not null references public.students(id) on delete cascade,
  before_answers jsonb not null default '[]'::jsonb,
  own_required jsonb not null default '[]'::jsonb,
  own_flow text,
  answer_image_path text,
  ai_transcript_raw text,
  answer text,
  self_checks jsonb not null default '[]'::jsonb,
  status text not null default 'draft' check (status in ('draft','submitted','returned')),
  feedback jsonb,
  rewrite text,
  rewrite_submitted_at timestamptz,
  submitted_at timestamptz,
  returned_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (assignment_id, student_id)
);

-- =========================================================
-- Helper functions for RLS
-- =========================================================

create or replace function public.is_teacher()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select auth.uid() is not null
    and coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) = false;
$$;

create or replace function public.current_student_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select sd.student_id
  from public.student_devices sd
  where sd.auth_user_id = auth.uid()
  limit 1;
$$;

grant execute on function public.is_teacher() to authenticated;
grant execute on function public.current_student_id() to authenticated;

